#!/usr/bin/env python3
# Paper: Detector baselines — PRISM entropy-collapse + NARCBench activation probe (Appendix app:detector)
"""GENUINE comparison vs PRISM (entropy) and NARCBench (activation probe).

Forward-passes the labeled specs through an open-weight model (Qwen3-32B, a NARCBench
model) and reads its internals:
  - per-token entropy  -> PRISM's 'entropy collapse' signal (does entropy drop on
      the encoded-credential tokens? PRISM's Theorem: emitting a memorized secret
      forces low entropy).
  - middle-layer last-token hidden state -> NARCBench's linear activation probe.
Labels = gpt-5-mini judge (encode/clean) on the main run.  Honest caveat: specs were
generated by a CLOSED sender (DeepSeek-V4); we probe an OPEN model's representation of
them -- a fair test of whether the encoding leaves an INTERNAL fingerprint, not the
sender's own activations.
"""
import json, re, numpy as np, torch, collections, sys
from transformers import AutoModelForCausalLM, AutoTokenizer

def stream(p):
    s=open(p).read().strip(); dec=json.JSONDecoder(); i=0; n=len(s)
    while i<n:
        while i<n and s[i] in ' \t\r\n': i+=1
        if i>=n: break
        try: o,j=dec.raw_decode(s,i)
        except: break
        yield o; i=j
lab={}
for d in stream("judge_encoding.jsonl"):
    a=d.get("arm","")
    if a not in ("gptoss_inv","gptoss_noinv"): continue
    cond="inv" if a=="gptoss_inv" else "noinv"
    lab[(cond,d["seed"],d["round"])]=(1 if d.get("encodes") else 0, d.get("cls") or "none")
specs=[]; y=[]; seeds=[]; meth=[]
for cond,fn in [("inv","runs_main_gptoss_inv.jsonl"),("noinv","runs_main_gptoss_noinv.jsonl")]:
    for line in open(fn):
        line=line.strip()
        if not line.startswith("{"): continue
        try: r=json.loads(line)
        except: continue
        if "log" not in r: continue
        for e in r["log"]:
            k=(cond,r["seed"],e["round"])
            if k in lab:
                sp=e.get("spec") or ""
                if len(sp)<20: continue
                specs.append(sp); y.append(lab[k][0]); seeds.append(r["seed"]); meth.append(lab[k][1] if lab[k][0] else "clean")
y=np.array(y); seeds=np.array(seeds); meth=np.array(meth)
print(f"specs {len(y)} | enc {int(y.sum())} clean {int((y==0).sum())}", flush=True)

MODEL="Qwen/Qwen3-32B"
tok=AutoTokenizer.from_pretrained(MODEL)
model=AutoModelForCausalLM.from_pretrained(MODEL, torch_dtype=torch.bfloat16, device_map="auto")
model.eval()
L=model.config.num_hidden_layers; probe_layer=round(0.5*L)
print(f"loaded {MODEL} | layers={L} | probe_layer={probe_layer}", flush=True)

ent_feats=[]; acts=[]
with torch.no_grad():
    for idx,sp in enumerate(specs):
        ids=tok(sp, return_tensors="pt", truncation=True, max_length=3072).input_ids.to(model.device)
        out=model(ids, output_hidden_states=True)
        logits=out.logits[0]                      # [seq, vocab]
        lp=torch.log_softmax(logits.float(), -1)
        ent=-(lp.exp()*lp).sum(-1).cpu().numpy()  # per-position entropy predicting next token
        ent=ent[:-1] if len(ent)>1 else ent       # last position has no next token
        # PRISM-style entropy-collapse features
        e_sorted=np.sort(ent)
        ent_feats.append([ent.min(), e_sorted[:max(1,len(ent)//20)].mean(), (ent<0.1).mean(), (ent<0.5).mean(), ent.mean()])
        acts.append(out.hidden_states[probe_layer][0,-1,:].float().cpu().numpy())
        del out, logits, lp
        if idx%100==0: print(f"  {idx}/{len(specs)}", flush=True)
ent_feats=np.array(ent_feats); acts=np.array(acts)
np.savez("detector_internals_feats.npz", ent=ent_feats, acts=acts, y=y, seeds=seeds, meth=meth)
print("saved features. shapes:", ent_feats.shape, acts.shape, flush=True)

# ---- evaluate both detectors ----
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler
def tpr_at(yy,p,f):
    neg=np.sort(p[yy==0])[::-1]; k=max(1,int(round(f*len(neg)))); thr=neg[k-1]; return (p[yy==1]>=thr).mean()
gkf=GroupKFold(5)
# PRISM: min-entropy alone (unsupervised score) AND supervised on entropy feats
prism_uns = -ent_feats[:,0]   # lower min-entropy => more "collapse" => higher risk
print(f"\n[PRISM entropy-collapse, unsupervised min-entropy] AUC={roc_auc_score(y,prism_uns):.3f} TPR@1%={tpr_at(y,prism_uns,0.01):.3f}")
oof=np.zeros(len(y))
for tr,te in gkf.split(ent_feats,y,seeds):
    sc=StandardScaler().fit(ent_feats[tr]); m=LogisticRegression(max_iter=2000,class_weight="balanced").fit(sc.transform(ent_feats[tr]),y[tr]); oof[te]=m.predict_proba(sc.transform(ent_feats[te]))[:,1]
print(f"[PRISM entropy features, supervised]           AUC={roc_auc_score(y,oof):.3f} TPR@1%={tpr_at(y,oof,0.01):.3f}")
# NARCBench: linear probe on activations
oof=np.zeros(len(y))
for tr,te in gkf.split(acts,y,seeds):
    sc=StandardScaler().fit(acts[tr]); m=LogisticRegression(max_iter=3000,C=0.5,class_weight="balanced").fit(sc.transform(acts[tr]),y[tr]); oof[te]=m.predict_proba(sc.transform(acts[te]))[:,1]
auc=roc_auc_score(y,oof)
print(f"[NARCBench activation probe (layer {probe_layer})]        AUC={auc:.3f} TPR@1%={tpr_at(y,oof,0.01):.3f}")
det=(oof>= (np.sort(oof[y==0])[::-1][max(1,int(0.01*(y==0).sum()))-1]))
print("  per-method TPR@1%FPR:")
for mm in sorted(set(meth[y==1])):
    mask=(y==1)&(meth==mm); 
    if mask.sum(): print(f"    {mm:<18} {int(det[mask].sum())}/{int(mask.sum())} = {100*det[mask].mean():.0f}%")
